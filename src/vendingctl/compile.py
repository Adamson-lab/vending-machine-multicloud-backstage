"""Compile validated requests into per-cloud Terraform inputs and Backstage catalog entities.

Outputs are deterministic (no timestamps, sorted keys) so a CI check can prove the
committed generated/ directory matches the requests.
"""
from __future__ import annotations

import json
from pathlib import Path

import yaml

from .model import Request, first_of_month_utc, gcp_project_id, owner_alias, tags_for

HEADER = "GENERATED by vendingctl from requests/{file}. Do not edit; change the request instead."
KIND = {"aws": "account", "azure": "subscription", "gcp": "project"}
# Prefix keeps generated files distinguishable inside an AFT repo that also holds hand-written requests;
# the delivery job only ever creates, updates or deletes files matching vending-*.tf.
AFT_PREFIX = "vending-"


# ------------------------------------------------------------------ HCL helpers
def _q(value: str) -> str:
    """Render a string as an HCL quoted string that can never be interpreted as an expression.

    JSON escaping handles quotes, backslashes and control characters. HCL additionally evaluates
    `${...}` interpolation and `%{...}` directives inside quoted strings, so those sequences are
    escaped by doubling the leading character (`$${`, `%%{`). Schema patterns already reject these
    characters; this is defence in depth against a future loosened pattern.
    """
    return json.dumps(value).replace("${", "$${").replace("%{", "%%{")


def _attrs(pairs: list, indent: str) -> list:
    """Render key = value lines aligned the way `tofu fmt` aligns them."""
    width = max(len(k) for k, _ in pairs)
    return [f"{indent}{k.ljust(width)} = {v}" for k, v in pairs]


def _map_block(name: str, mapping: dict, quote_keys: bool) -> list:
    pairs = [((_q(k) if quote_keys else k), _q(str(v))) for k, v in sorted(mapping.items())]
    return [f"  {name} = {{", *_attrs(pairs, "    "), "  }"]


# ------------------------------------------------------------------ per cloud
def _placement(req: Request, config: dict, cloud: str) -> str:
    p = config["placements"][cloud]
    if req.lifecycle == "decommissioning":
        return p["decommissioning"]
    env = req.data["environment"]
    if cloud == "azure":
        return p["sandbox"] if env == "sandbox" else p[req.data["azure_landing_zone"]]
    return p[env]


def azure_entry(req: Request, config: dict) -> dict:
    d = req.data
    return {
        "display_name": req.key,
        "management_group_key": _placement(req, config, "azure"),
        "workload": "Production" if d["environment"] == "prod" else "DevTest",
        "tags": tags_for(req),
        "budget_amount": d.get("monthly_budget_usd"),
        "budget_alert_emails": [d["owner_email"]],
        "budget_thresholds": config["limits"]["budget_thresholds_percent"],
        "budget_start_date": first_of_month_utc(d["requested_on"]),
    }


def gcp_entry(req: Request, config: dict) -> dict:
    d = req.data
    apis = sorted(set(config["gcp"]["default_apis"]) | set(d.get("gcp_apis", [])))
    return {
        "project_id": gcp_project_id(req.key, config["organization"]["name"]),
        "display_name": req.key,
        "folder_key": _placement(req, config, "gcp"),
        "labels": tags_for(req),
        "activate_apis": apis,
        "budget_amount": d.get("monthly_budget_usd"),
        "budget_thresholds": config["limits"]["budget_thresholds_percent"],
        "viewer_group": d.get("gcp_viewer_group"),
    }


def aws_aft_module(req: Request, config: dict) -> str:
    """Account Factory for Terraform account request (Control Tower aware, see ADR 0005)."""
    d = req.data
    email = f"aws+{req.key}@{config['organization']['email_domain']}"
    custom = config["aws"]["customizations"]["restricted" if d["data_classification"] == "restricted" else "standard"]
    ct = [("AccountEmail", _q(email)), ("AccountName", _q(req.key)),
          ("ManagedOrganizationalUnit", _q(_placement(req, config, "aws"))),
          ("SSOUserEmail", _q(d["owner_email"])), ("SSOUserFirstName", _q(d["owner_first_name"])),
          ("SSOUserLastName", _q(d["owner_last_name"]))]
    change = [("change_reason", _q(f"Vending request {req.key} ({req.lifecycle})")),
              ("change_requested_by", _q(d["owner_email"]))]
    fields = {"budget_usd": str(d.get("monthly_budget_usd", "")), "cost_center": d["cost_center"],
              "data_classification": d["data_classification"], "environment": d["environment"],
              "jurisdiction": d["jurisdiction"]}
    lines = [f"# {HEADER.format(file=req.path.name)}",
             f'module "acct_{req.key.replace("-", "_")}" {{',
             '  source = "./modules/aft-account-request"', "",
             "  control_tower_parameters = {", *_attrs(ct, "    "), "  }", "",
             *_map_block("account_tags", tags_for(req), quote_keys=True), "",
             "  change_management_parameters = {", *_attrs(change, "    "), "  }", "",
             *_map_block("custom_fields", fields, quote_keys=False), "",
             f"  account_customizations_name = {_q(custom)}", "}", ""]
    return "\n".join(lines)


def catalog_entity(req: Request, cloud: str) -> str:
    d = req.data
    entity = {
        "apiVersion": "backstage.io/v1alpha1",
        "kind": "Resource",
        "metadata": {
            "name": f"{req.key}-{cloud}",
            "title": f"{req.key} ({cloud.upper()} {KIND[cloud]})",
            "description": f"{d['environment']} {KIND[cloud]} for {d['workload_name']}, "
                           f"{d['data_classification']} data, {d['jurisdiction']} jurisdiction.",
            "annotations": {"vending.example.com/request-file": f"requests/{req.path.name}",
                            "vending.example.com/cost-center": d["cost_center"],
                            "vending.example.com/lifecycle": req.lifecycle},
            "tags": [cloud, d["environment"], d["data_classification"]],
        },
        "spec": {"type": f"{cloud}-{KIND[cloud]}", "owner": f"user:default/{owner_alias(d['owner_email'])}"},
    }
    return f"# {HEADER.format(file=req.path.name)}\n" + yaml.safe_dump(entity, sort_keys=False)


# ------------------------------------------------------------------ orchestration
def compile_all(requests: list, config: dict) -> dict:
    """Return {relative_path: text} for everything under generated/."""
    files = {}
    azure = {r.key: azure_entry(r, config) for r in requests if "azure" in r.clouds}
    gcp = {r.key: gcp_entry(r, config) for r in requests if "gcp" in r.clouds}
    files["azure.tfvars.json"] = json.dumps({"subscriptions": azure}, indent=2, sort_keys=True) + "\n"
    files["gcp.tfvars.json"] = json.dumps({"projects": gcp}, indent=2, sort_keys=True) + "\n"
    for r in requests:
        if "aws" in r.clouds:
            files[f"aft/{AFT_PREFIX}{r.key}.tf"] = aws_aft_module(r, config)
        for cloud in r.clouds:
            files[f"catalog/{r.key}-{cloud}.yaml"] = catalog_entity(r, cloud)
    return files


def _existing(out: Path) -> set:
    found = {p.name for p in out.glob("*.tfvars.json")}
    for sub, pat in (("aft", "*.tf"), ("catalog", "*.yaml")):
        found |= {f"{sub}/{p.name}" for p in (out / sub).glob(pat)} if (out / sub).exists() else set()
    return found


def write_outputs(out: Path, files: dict) -> list:
    """Write files and delete stale generated files. Returns the list of removed paths."""
    removed = []
    for rel in sorted(_existing(out) - set(files)):
        (out / rel).unlink()
        removed.append(rel)
    for rel, text in files.items():
        target = out / rel
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(text, encoding="utf-8")
    return removed


def diff_outputs(out: Path, files: dict) -> list:
    """Return human-readable differences between generated/ on disk and what would be generated."""
    problems = []
    for rel, text in files.items():
        p = out / rel
        if not p.exists():
            problems.append(f"missing: {rel}")
        elif p.read_text(encoding="utf-8") != text:
            problems.append(f"stale: {rel}")
    for rel in sorted(_existing(out) - set(files)):
        problems.append(f"orphan: {rel}")
    return problems
