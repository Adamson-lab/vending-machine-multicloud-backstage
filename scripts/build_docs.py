#!/usr/bin/env python3
"""Generate documents that must never drift from their sources.

  docs/03-architecture-views/architecture-views.md  <- diagrams/*.mmd
  docs/container-inventory.md                       <- requests/*.yaml + config

Usage: build_docs.py [--check]   (--check exits 1 if generated files are stale)
"""
import argparse
import sys
from pathlib import Path

from vendingctl import compile as comp, expire
from vendingctl.model import ROOT, load_config, load_requests

VIEWS = [
    ("D01-system-context", "System context", "Who uses the vending machine and which systems it touches.", "Business, architects"),
    ("D02-architecture", "Container architecture", "How a request becomes Terraform inputs, AFT requests and catalog entries.", "Architects, engineers"),
    ("D03-request-lifecycle-sequence", "Request lifecycle sequence", "From portal form to provisioned container, with validation, approval and apply.", "Workload teams, engineers"),
    ("D04-request-state-machine", "Request state machine", "The states a request can be in and what moves it.", "Engineers, auditors"),
    ("D05-approval-routing", "Approval routing", "Which approver roles a request triggers.", "Approvers, governance"),
    ("D06-state-and-blast-radius", "State layout and blast radius", "One state per cloud and the sharding trigger.", "Engineers, operations"),
    ("D07-aws-aft-flow", "AWS Account Factory flow", "Why AWS accounts go through AFT and Control Tower.", "Engineers, security"),
    ("D08-credentials-flow", "Pipeline credentials", "Federated credentials with separate plan and apply identities.", "Security, engineers"),
    ("D09-decommission-flow", "Expiry and decommissioning", "Sandbox expiry, quarantine and manual deletion.", "Operations, finance"),
    ("D10-failure-dependencies", "Failure and dependency view", "What breaks when each dependency fails.", "Operations, risk"),
    ("D11-backstage-integration", "Backstage integration", "Template, built-in actions and catalog publication.", "Platform, developers"),
    ("D12-roadmap", "Delivery roadmap", "Indicative sequencing. Dates are planning placeholders.", "Executives, programme"),
    ("D13-data-model", "Conceptual data model", "Request, placement, approval, exception, catalog resource.", "Architects, data"),
    ("D14-current-target-transition", "Current, transition and target state", "Why adoption is staged.", "Executives, architects"),
    ("D15-capability-map", "Capability map", "Capabilities the vending machine provides.", "Business, executives"),
]


def render_views() -> str:
    out = ["# Architecture views", "",
           "<!-- GENERATED by scripts/build_docs.py from diagrams/*.mmd. Do not edit by hand. -->", "",
           "Diagram sources are in `diagrams/`.", "", "| ID | View | Audience |", "|---|---|---|"]
    out += [f"| {s.split('-')[0]} | {t} | {a} |" for s, t, _, a in VIEWS]
    out.append("")
    for stem, title, purpose, aud in VIEWS:
        src = (ROOT / "diagrams" / f"{stem}.mmd").read_text(encoding="utf-8").rstrip()
        out += [f"## {stem.split('-')[0]} {title}", "", f"**Purpose:** {purpose}  ", f"**Audience:** {aud}  ",
                f"**Source:** `diagrams/{stem}.mmd`", "", "```mermaid", src, "```", ""]
    return "\n".join(out)


def render_inventory() -> str:
    cfg = load_config()
    reqs = load_requests(ROOT / "requests")
    out = ["# Container inventory", "",
           "<!-- GENERATED by scripts/build_docs.py from requests/*.yaml. Do not edit by hand. -->", "",
           f"{len(reqs)} request(s). Placement values are logical keys resolved against the landing zone outputs.", "",
           "| Key | Environment | Data class | Lifecycle | AWS OU | Azure group | GCP folder | Budget USD | Expires |",
           "|---|---|---|---|---|---|---|---|---|"]
    for r in reqs:
        d = r.data
        def place(cloud):
            return comp._placement(r, cfg, cloud) if cloud in r.clouds else "-"
        e = expire.expiry_date(r)
        out.append(f"| {r.key} | {d['environment']} | {d['data_classification']} | {r.lifecycle} | {place('aws')} | "
                   f"{place('azure')} | {place('gcp')} | {d.get('monthly_budget_usd', '-')} | {e.isoformat() if e else '-'} |")
    return "\n".join(out)


TARGETS = {"docs/03-architecture-views/architecture-views.md": render_views, "docs/container-inventory.md": render_inventory}


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    stale = []
    for rel, fn in TARGETS.items():
        path, text = ROOT / rel, fn().rstrip() + "\n"
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != text:
                stale.append(rel)
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text, encoding="utf-8")
            print("wrote", rel)
    if stale:
        print("STALE generated docs (run scripts/build_docs.py):", *stale, sep="\n  ", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
